#!/usr/bin/env python3
"""Generates the Reown legacy-storage test fixtures with the real SQLCipher library.

The removed Reown SDK (com.reown 1.6.9) stored WalletConnect state in two SQLCipher 4 databases opened
by sqlcipher-android with a random 32-byte binary passphrase. This script reproduces that with the
SQLCipher C library (Homebrew `sqlcipher`, community edition, same 4.x defaults) through ctypes, so the
passphrase is passed as raw bytes exactly as sqlcipher-android passes it to sqlite3_key.

Usage: python3 -I make-reown-legacy-fixtures.py <output dir> [path to libsqlcipher.dylib]

Every key, topic and passphrase here is synthetic test data generated by this script. It writes:
  reown-sign.db / reown-core.db      SQLCipher defaults (PBKDF2-HMAC-SHA512 x 256,000, 4 KiB pages)
  journal.db + journal.db-journal    a transaction cut off mid-write (rollback journal left behind)
  wal.db + wal.db-wal                committed frames still in the write-ahead log
  plain.db                           an unencrypted database covering the record and b-tree formats
  fixtures.json                      passphrases, key chain and the rows each table must read back as
"""
import ctypes
import hashlib
import json
import os
import random
import shutil
import sys

SQLITE_ROW = 100
SQLITE_DONE = 101
SQLITE_OK = 0

INTEGER, FLOAT, TEXT, BLOB, NULL = 1, 2, 3, 4, 5


LONG_VALUE = 512  # longer values are recorded by length and SHA-256 to keep fixtures.json small


def long_value(data):
    return {"length": len(data), "sha256": hashlib.sha256(data).hexdigest()}


class Db:
    def __init__(self, lib, path, passphrase=None, kdf_iter=None):
        self.lib = lib
        self.handle = ctypes.c_void_p()
        flags = 0x00000002 | 0x00000004  # READWRITE | CREATE
        rc = lib.sqlite3_open_v2(path.encode(), ctypes.byref(self.handle), flags, None)
        if rc != SQLITE_OK:
            raise RuntimeError(f"open {path}: {rc}")
        if passphrase is not None:
            rc = lib.sqlite3_key(self.handle, passphrase, len(passphrase))
            if rc != SQLITE_OK:
                raise RuntimeError(f"key {path}: {rc}")
        if kdf_iter is not None:
            self.execute(f"PRAGMA kdf_iter = {kdf_iter}")

    def execute(self, sql, params=()):
        stmt = ctypes.c_void_p()
        rc = self.lib.sqlite3_prepare_v2(self.handle, sql.encode(), -1, ctypes.byref(stmt), None)
        if rc != SQLITE_OK:
            raise RuntimeError(f"prepare {sql!r}: {self.lib.sqlite3_errmsg(self.handle)}")
        try:
            for index, value in enumerate(params, start=1):
                self._bind(stmt, index, value)
            rows = []
            while True:
                rc = self.lib.sqlite3_step(stmt)
                if rc == SQLITE_DONE:
                    return rows
                if rc != SQLITE_ROW:
                    raise RuntimeError(f"step {sql!r}: {self.lib.sqlite3_errmsg(self.handle)}")
                rows.append([self._column(stmt, i) for i in range(self.lib.sqlite3_column_count(stmt))])
        finally:
            self.lib.sqlite3_finalize(stmt)

    def _bind(self, stmt, index, value):
        if value is None:
            self.lib.sqlite3_bind_null(stmt, index)
        elif isinstance(value, bool) or isinstance(value, int):
            self.lib.sqlite3_bind_int64(stmt, index, ctypes.c_int64(int(value)))
        elif isinstance(value, float):
            self.lib.sqlite3_bind_double(stmt, index, ctypes.c_double(value))
        elif isinstance(value, bytes):
            self.lib.sqlite3_bind_blob(stmt, index, value, len(value), ctypes.c_void_p(-1))
        else:
            data = str(value).encode("utf-8")
            self.lib.sqlite3_bind_text(stmt, index, data, len(data), ctypes.c_void_p(-1))

    def _column(self, stmt, i):
        kind = self.lib.sqlite3_column_type(stmt, i)
        if kind == INTEGER:
            return {"int": self.lib.sqlite3_column_int64(stmt, i)}
        if kind == FLOAT:
            return {"float": self.lib.sqlite3_column_double(stmt, i)}
        if kind == NULL:
            return None
        size = self.lib.sqlite3_column_bytes(stmt, i)
        if kind == TEXT:
            data = ctypes.string_at(self.lib.sqlite3_column_text(stmt, i), size)
            return {"text": data.decode("utf-8")} if size <= LONG_VALUE else long_value(data)
        data = ctypes.string_at(self.lib.sqlite3_column_blob(stmt, i), size) if size else b""
        return {"blob": data.hex()} if size <= LONG_VALUE else long_value(data)

    def table_rows(self, table):
        columns = [row[1]["text"] for row in self.execute(f"PRAGMA table_info({table})")]
        quoted = ", ".join('"' + column.replace('"', '""') + '"' for column in columns)
        rows = self.execute(f"SELECT {quoted} FROM {table} ORDER BY rowid")
        return {"columns": columns, "rows": rows}

    def close(self):
        self.lib.sqlite3_close(self.handle)


def load(path):
    lib = ctypes.CDLL(path)
    lib.sqlite3_open_v2.argtypes = [ctypes.c_char_p, ctypes.POINTER(ctypes.c_void_p), ctypes.c_int, ctypes.c_char_p]
    lib.sqlite3_key.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_int]
    lib.sqlite3_prepare_v2.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_int,
                                       ctypes.POINTER(ctypes.c_void_p), ctypes.c_void_p]
    lib.sqlite3_errmsg.argtypes = [ctypes.c_void_p]
    lib.sqlite3_errmsg.restype = ctypes.c_char_p
    lib.sqlite3_step.argtypes = [ctypes.c_void_p]
    lib.sqlite3_finalize.argtypes = [ctypes.c_void_p]
    lib.sqlite3_column_count.argtypes = [ctypes.c_void_p]
    for name in ["sqlite3_column_type", "sqlite3_column_bytes"]:
        getattr(lib, name).argtypes = [ctypes.c_void_p, ctypes.c_int]
    lib.sqlite3_column_int64.argtypes = [ctypes.c_void_p, ctypes.c_int]
    lib.sqlite3_column_int64.restype = ctypes.c_int64
    lib.sqlite3_column_double.argtypes = [ctypes.c_void_p, ctypes.c_int]
    lib.sqlite3_column_double.restype = ctypes.c_double
    lib.sqlite3_column_text.argtypes = [ctypes.c_void_p, ctypes.c_int]
    lib.sqlite3_column_text.restype = ctypes.c_void_p
    lib.sqlite3_column_blob.argtypes = [ctypes.c_void_p, ctypes.c_int]
    lib.sqlite3_column_blob.restype = ctypes.c_void_p
    lib.sqlite3_bind_null.argtypes = [ctypes.c_void_p, ctypes.c_int]
    lib.sqlite3_bind_int64.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_int64]
    lib.sqlite3_bind_double.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_double]
    lib.sqlite3_bind_text.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_void_p]
    lib.sqlite3_bind_blob.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_void_p]
    lib.sqlite3_close.argtypes = [ctypes.c_void_p]
    return lib


